<?php
// Tinh (latin-ext \ (latin U vietnamese)) de hen thu hep unicode-range cua subset latin-ext:
// glyph nao da co trong latin/vietnamese thi khong duoc keu file 85KB cua latin-ext.
$latinExt = [[0x0100,0x02BA],[0x02BD,0x02C5],[0x02C7,0x02CC],[0x02CE,0x02D7],[0x02DD,0x02FF],[0x0304,0x0304],[0x0308,0x0308],[0x0329,0x0329],[0x1D00,0x1DBF],[0x1E00,0x1E9F],[0x1EF2,0x1EFF],[0x2020,0x2020],[0x20A0,0x20AB],[0x20AD,0x20C4],[0x2113,0x2113],[0x2C60,0x2C7F],[0xA720,0xA7FF]];
$covered = [[0x0000,0x00FF],[0x0131,0x0131],[0x0152,0x0153],[0x02BB,0x02BC],[0x02C6,0x02C6],[0x02DA,0x02DA],[0x02DC,0x02DC],[0x0304,0x0304],[0x0308,0x0308],[0x0329,0x0329],[0x2000,0x206F],[0x20AC,0x20AC],[0x2122,0x2122],[0x2191,0x2191],[0x2193,0x2193],[0x2212,0x2212],[0x2215,0x2215],[0xFEFF,0xFEFF],[0xFFFD,0xFFFD],
    [0x0102,0x0103],[0x0110,0x0111],[0x0128,0x0129],[0x0168,0x0169],[0x01A0,0x01A1],[0x01AF,0x01B0],[0x0300,0x0301],[0x0303,0x0304],[0x0308,0x0309],[0x0323,0x0323],[0x0329,0x0329],[0x1EA0,0x1EF9],[0x20AB,0x20AB]];

$out = [];
foreach ($latinExt as [$a, $b]) {
    $parts = [[$a, $b]];
    foreach ($covered as [$ca, $cb]) {
        $next = [];
        foreach ($parts as [$pa, $pb]) {
            if ($cb < $pa || $ca > $pb) { $next[] = [$pa, $pb]; continue; }
            if ($ca > $pa) $next[] = [$pa, min($pb, $ca - 1)];
            if ($cb < $pb) $next[] = [max($pa, $cb + 1), $pb];
        }
        $parts = $next;
    }
    foreach ($parts as [$pa, $pb]) $out[] = [$pa, $pb];
}
sort($out);
$fmt = fn(int $cp) => 'U+' . strtoupper(str_pad(dechex($cp), 4, '0', STR_PAD_LEFT));
$segs = [];
foreach ($out as $o) {
    $a = $o[0]; $b = $o[1];
    $segs[] = $a === $b ? $fmt($a) : $fmt($a) . '-' . $fmt($b);
}
$total = 0;
foreach ($out as $o) $total += $o[1] - $o[0] + 1;
echo 'so dai: ', count($out), ' | so codepoint con lai: ', $total, PHP_EOL;
echo implode(', ', $segs), PHP_EOL;
